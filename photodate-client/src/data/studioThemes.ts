export function studioTokens(id: string): Record<string, string> {
  const [bg, surface, raised, border, accent, button, text, muted, companion] =
    palettes[id] ?? palettes.classic;
  return {
    "--c-bg": bg,
    "--c-surface-1": surface,
    "--c-surface-2": raised,
    "--c-surface-3": border,
    "--c-border": border,
    "--c-border-soft": `${border}88`,
    "--c-text-hi": text,
    "--c-text-md": muted,
    "--c-text-lo": muted,
    "--c-accent": accent,
    "--c-accent-dim": button,
    "--c-accent-glow": `${accent}33`,
    "--c-accent-soft": `${accent}18`,
    "--c-accent-border": `${accent}77`,
    "--studio-button": button,
    "--studio-companion": companion,
    "--studio-display": ["vintage", "noir", "scrapbook"].includes(id)
      ? "Georgia, serif"
      : "Inter, system-ui, sans-serif",
  };
}
